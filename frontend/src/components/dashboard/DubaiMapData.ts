export function placeToMonitoringUnit(place: DubaiPlace): MonitoringUnit {
  return {
    id: place.id,
    name: place.name,
    districtId: 'dis-dxb',
    districtName: 'Dubai Emirate',
    unitType:
      place.category === 'industrial'
        ? 'construction'
        : place.category === 'worker_zone'
        ? 'accommodation'
        : place.category === 'logistics'
        ? 'logistics'
        : 'office',
    latitude: DUBAI_COORDINATES[place.id][0],
    longitude: DUBAI_COORDINATES[place.id][1],
    headcountBand: place.workforceCount,
    currentTier: place.tier === 'NORMAL' ? null : place.tier,
    completeness: 94,
    openAlertCount: place.tier === 'ACTION' ? 2 : place.tier === 'ALERT' ? 1 : 0,
    feedStatus: 'ok',
    primaryRiskReason: place.primaryRisk,
    observedTrendPercent: parseInt(place.caseTrend) || 12,
  };
}

